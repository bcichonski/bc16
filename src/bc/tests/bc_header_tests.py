import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
BC = os.path.join(HERE, '..', 'bc.py')
ASM = os.path.join(HERE, '..', '..', 'bc81asmc', 'bc81asmc.py')
PROGRAM = 'byte main() { return 1; }\n'


def run_tool(script, args, cwd):
    '''Runs a tool script with the current interpreter; fails the test on a non-zero exit.'''
    res = subprocess.run([sys.executable, script] + args, cwd=cwd, capture_output=True, text=True)
    return res


class GeneratedHeaderTests(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.tmp = tmp.name

    def compile_program(self, folder):
        os.makedirs(folder, exist_ok=True)
        src = os.path.join(folder, 'prog.b')
        with open(src, 'w', encoding='utf8') as f:
            f.write(PROGRAM)
        res = run_tool(BC, [src], folder)
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        with open(os.path.join(folder, 'prog.basm'), encoding='utf8') as f:
            return f.read()

    def test_basm_first_line_is_header_naming_source(self):
        basm = self.compile_program(os.path.join(self.tmp, 'compiled'))
        self.assertEqual(basm.splitlines()[0], '; generated by bc from prog.b - do not edit')

    def test_header_adds_no_bytes_to_btap(self):
        with_header = os.path.join(self.tmp, 'with')
        basm = self.compile_program(with_header)
        header, body = basm.split('\n', 1)
        self.assertTrue(header.startswith('; generated by bc from prog.b'))

        # Same file name in a second folder, so the btap preamble (which uses the name) matches.
        without_header = os.path.join(self.tmp, 'without')
        os.makedirs(without_header)
        without_path = os.path.join(without_header, 'prog.basm')
        with open(without_path, 'w', encoding='utf8') as f:
            f.write(body)

        for folder in (with_header, without_header):
            res = run_tool(ASM, [os.path.join(folder, 'prog.basm'), '--btap'], folder)
            self.assertEqual(res.returncode, 0, res.stdout + res.stderr)

        with open(os.path.join(with_header, 'prog.btap'), 'rb') as f:
            with_bytes = f.read()
        with open(os.path.join(without_header, 'prog.btap'), 'rb') as f:
            without_bytes = f.read()
        self.assertEqual(with_bytes, without_bytes)


if __name__ == '__main__':
    unittest.main()
